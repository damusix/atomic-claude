// OMP's rule scan skips files any Git ignore source covers, so the flat card
// files stay unignored (docs/spec/omp-plugin-compatibility.md).
const (
	// ProjectRulesDir is the repository-relative OMP project rule directory.
	ProjectRulesDir = ".omp/rules"
	// cardFilePrefix and the `.md` suffix bracket the domain in a card's file
	// name, which keeps the generated files apart from the repository's own rules.
	cardFilePrefix = "atomic-wiki-"
	// cardMarker is the frontmatter comment that marks a file as Atomic's, so a
	// card dropped from the projection is recognised without a ledger.
	cardMarker = "# generated by atomic; do not hand-edit"
	// legacyNestedCards and legacyNestedIgnoreRule are the nested copy OMP never
	// listed.
	legacyNestedCards      = ".omp/rules/atomic/wiki"
	legacyNestedIgnoreRule = "/rules/atomic/"
)

// ShippedRule is one shipped rule's OMP projection.
type ShippedRule struct {
	// RecordID is the producer-qualified canonical identity.
	RecordID string
	// Class is the record class.
	Class rules.Class
	// Source is the producer-relative authored source path and, for OMP, the
	// package-relative native path: the rule ships where the corpus declares it.
	Source string
	// SourceDigest is the digest of the authored source bytes.
	SourceDigest string
	// NativeResource is the package-relative native path.
	NativeResource string
	// Bytes is the authored rule bytes, shipped verbatim.
	Bytes []byte
	// Digest is the projection digest of Bytes.
	Digest string
	// Scope is the selected native scope mapping. It is empty whenever no
	// proven role maps the record, which is every record for OMP 18.1.18.
	Scope []rules.ScopeField
	// Delivery is how OMP would supply the matched body at runtime.
	Delivery rules.RuntimeDelivery
	// Tier is the strongest native guarantee the capability record proves.
	Tier artifacts.EnforcementTier
	// Order is the record's position in the projected generation, ascending by
	// RecordID.
	Order int
}

// ShippedRuleReport is the shipped corpus's OMP rule projection plus the
// rule-delivery surfaces OMP cannot promise.
type ShippedRuleReport struct {
	// Ordering names the deterministic generation order.
	Ordering string
	Rules    []ShippedRule
	// Gaps are the rule-delivery surfaces the record leaves unproven.
	Gaps []harness.Capability
}

// ProjectShippedRules renders the shipped rule corpus for OMP. Bytes ship
// verbatim because OMP rule files use the same `paths:` frontmatter.
func ProjectShippedRules(cat *artifacts.Catalog, m harness.CapabilityMatrix) (ShippedRuleReport, error) {
	if m.Harness != harness.KindOMP {
		return ShippedRuleReport{}, fmt.Errorf("omp: shipped rule projection needs the OMP capability record, got %q", m.Harness)
	}
	sources, err := ShippedRuleSources(cat)
	if err != nil {
		return ShippedRuleReport{}, err
	}
	return projectShippedRules(sources, m)
}

// ShippedRuleSources pairs every path-scoped rule with its bytes. The projection
// and runtime delivery share the pairs so neither can miss a rule.
func ShippedRuleSources(cat *artifacts.Catalog) ([]harness.RuleSource, error) {
	return harness.ShippedRuleSources(cat)
}

func projectShippedRules(sources []harness.RuleSource, m harness.CapabilityMatrix) (ShippedRuleReport, error) {
	records := make([]rules.RuleRecord, 0, len(sources))
	for i, s := range sources {
		if s.Record.ID == "" {
			return ShippedRuleReport{}, fmt.Errorf("omp: rule source %d has no record identity", i)
		}
		if s.Record.Producer != rules.ProducerShipped {
			return ShippedRuleReport{}, fmt.Errorf("omp: %s is not a shipped rule", s.Record.ID)
		}
		if got := managedfile.Digest(s.Bytes); got != s.Record.SourceDigest {
			return ShippedRuleReport{}, fmt.Errorf("omp: project %s: source bytes digest %s does not match record digest %s", s.Record.ID, got, s.Record.SourceDigest)
		}
		records = append(records, s.Record)
	}
	if err := rules.Validate(records); err != nil {
		return ShippedRuleReport{}, err
	}

	ordered := make([]harness.RuleSource, len(sources))
	copy(ordered, sources)
	sort.SliceStable(ordered, func(i, j int) bool { return ordered[i].Record.ID < ordered[j].Record.ID })

	ev := harness.RuleEvidence(m)
	report := ShippedRuleReport{
		Ordering: harness.RuleOrderingRecordID,
		Gaps:     harness.RuleGaps(m),
	}
	for i, s := range ordered {
		sel := rules.Select(s.Record, artifacts.TargetOMP, ev)
		report.Rules = append(report.Rules, ShippedRule{
			RecordID:       s.Record.ID,
			Class:          s.Record.Class,
			Source:         s.Record.Source,
			SourceDigest:   s.Record.SourceDigest,
			NativeResource: s.Record.Source,
			Bytes:          s.Bytes,
			Digest:         artifacts.ProjectionDigest(s.Bytes),
			Scope:          sel.Scope,
			Delivery:       sel.Delivery,
			Tier:           sel.Tier,
			Order:          i,
		})
	}
	return report, nil
}

// Card is one projected native pointer card in a repository's OMP project rule
// surface.
type Card struct {
	RecordID string
	Domain   string
	// Name is the card's file name inside the cards directory.
	Name  string
	Bytes []byte
	// LinkTarget is the relative link text to the canonical card; empty means a
	// generated copy of Bytes.
	LinkTarget string
	// CardPath is the canonical card's repository-relative slash path, set with LinkTarget.
	CardPath string
	// CopyDigest is the digest of Bytes, which earlier versions published.
	CopyDigest   string
	SourceDigest string
	// Digest is what the native entry must hold: the link text for a link,
	// else Bytes.
	Digest   string
	Scope    []rules.ScopeField
	Delivery rules.RuntimeDelivery
	Tier     artifacts.EnforcementTier
}

// ProjectCards is one repository's projected OMP card generation.
type ProjectCards struct {
	ProjectKey string
	// Base is the absolute, symlink-resolved repository (or worktree) root the
	// cards bind to.
	Base string
	// Dir is the absolute OMP rule directory under the resolved base; the cards
	// are files in it beside the repository's own rules.
	Dir string
	// StateDir is the state root relative to Base; empty when the state root
	// lies outside Base and cards publish as copies.
	StateDir string
	Cards    []Card
	// Instances are the rule bindings, aligned with Cards order: each
	// immutable record bound to this project key and the resolved base.
	Instances []rules.RuleInstance
	// Generation is the card set's content identity.
	Generation string
	// Gaps are the rule-delivery surfaces the projection cannot promise.
	Gaps []harness.Capability
}

// LoadProjectCards reads one repository's wiki pointer cards from its state root
// and projects them onto the OMP project rule surface, writing nothing.
func LoadProjectCards(stateRoot, projectKey, base string, m harness.CapabilityMatrix) (ProjectCards, error) {
	if stateRoot == "" {
		return ProjectCards{}, fmt.Errorf("omp: project cards: empty state root")
	}
	rulesRoot := filepath.Join(stateRoot, "rules")
	records, err := rules.LoadWiki(rulesRoot, projectKey)
	if err != nil {
		return ProjectCards{}, err
	}
	sources := make([]harness.RuleSource, 0, len(records))
	for _, rec := range records {
		source := filepath.Join(rulesRoot, filepath.FromSlash(strings.TrimPrefix(rec.Source, "rules/")))
		data, err := os.ReadFile(source)
		if err != nil {
			return ProjectCards{}, fmt.Errorf("omp: read card %s: %w", rec.Source, err)
		}
		sources = append(sources, harness.RuleSource{Record: rec, Bytes: data})
	}
	cards, err := BuildProjectCards(sources, projectKey, base, m)
	if err != nil {
		return ProjectCards{}, err
	}
	state, err := filepath.Abs(stateRoot)
	if err != nil {
		return ProjectCards{}, err
	}
	if resolved, err := filepath.EvalSymlinks(state); err == nil {
		state = resolved
	}
	rel, inside := config.RepoRelative(cards.Base, state)
	if !inside {
		return cards, nil
	}
	cards.StateDir = rel
	for i := range cards.Cards {
		c := &cards.Cards[i]
		c.CardPath = cards.cardPath(c.Domain)
		c.LinkTarget = cards.linkTarget(c.Domain)
		c.Digest = managedfile.Digest([]byte(c.LinkTarget))
	}
	cards.Generation = cardGeneration(cards.Cards)
	return cards, nil
}

// BuildProjectCards projects bound wiki pointer card records onto the OMP
// project rule surface, offline and deterministically.
func BuildProjectCards(sources []harness.RuleSource, projectKey, base string, m harness.CapabilityMatrix) (ProjectCards, error) {
	if m.Harness != harness.KindOMP {
		return ProjectCards{}, fmt.Errorf("omp: card projection needs the OMP capability record, got %q", m.Harness)
	}
	if projectKey == "" {
		return ProjectCards{}, fmt.Errorf("omp: card projection: empty project key")
	}
	if !filepath.IsAbs(base) {
		return ProjectCards{}, fmt.Errorf("omp: card projection: base %q is not absolute", base)
	}

	resolved, err := filepath.EvalSymlinks(filepath.Clean(base))
	if err != nil {
		return ProjectCards{}, fmt.Errorf("omp: card projection: resolve base %q: %w", base, err)
	}
	cards := ProjectCards{
		ProjectKey: projectKey,
		Base:       resolved,
		Dir:        filepath.Join(resolved, filepath.FromSlash(ProjectRulesDir)),
		Gaps:       harness.RuleGaps(m),
	}

	ordered := make([]harness.RuleSource, len(sources))
	copy(ordered, sources)
	sort.SliceStable(ordered, func(i, j int) bool { return ordered[i].Record.ID < ordered[j].Record.ID })

	records := make([]rules.RuleRecord, 0, len(ordered))
	for i, s := range ordered {
		if s.Record.ID == "" {
			return ProjectCards{}, fmt.Errorf("omp: card source %d has no record identity", i)
		}
		if s.Record.Producer != rules.ProducerWiki {
			return ProjectCards{}, fmt.Errorf("omp: %s is not a repository wiki card", s.Record.ID)
		}
		if got := managedfile.Digest(s.Bytes); got != s.Record.SourceDigest {
			return ProjectCards{}, fmt.Errorf("omp: project %s: source bytes digest %s does not match record digest %s", s.Record.ID, got, s.Record.SourceDigest)
		}
		records = append(records, s.Record)
	}
	if err := rules.Validate(records); err != nil {
		return ProjectCards{}, err
	}

	// Worktrees share record identity but not bases; the resolved base makes a
	// symlinked checkout publish to one location.
	if len(records) > 0 {
		instances, err := rules.BindAll(records, projectKey, base)
		if err != nil {
			return ProjectCards{}, err
		}
		cards.Instances = instances
	}
	ev := harness.RuleEvidence(m)
	for _, s := range ordered {
		domain := cardDomain(s.Record)
		if domain == "" || strings.Contains(domain, "/") || domain == "." || domain == ".." {
			return ProjectCards{}, fmt.Errorf("omp: card %s has no usable domain", s.Record.ID)
		}
		sel := rules.Select(s.Record, artifacts.TargetOMP, ev)
		projected := projectCardBytes(domain, s.Record)
		cards.Cards = append(cards.Cards, Card{
			RecordID:     s.Record.ID,
			Domain:       domain,
			Name:         cardFilePrefix + domain + ".md",
			Bytes:        projected,
			CopyDigest:   artifacts.ProjectionDigest(projected),
			SourceDigest: s.Record.SourceDigest,
			Digest:       artifacts.ProjectionDigest(projected),
			Scope:        sel.Scope,
			Delivery:     sel.Delivery,
			Tier:         sel.Tier,
		})
	}
	cards.Generation = cardGeneration(cards.Cards)
	return cards, nil
}

// cardDomain reads a wiki record's domain from its producer-relative source,
// which rules.ParseWiki already validates as rules/wiki/<domain>.md.
func cardDomain(r rules.RuleRecord) string {
	return strings.TrimSuffix(strings.TrimPrefix(r.Source, "rules/wiki/"), ".md")
}

// cardGeneration is the card set's content identity over each card's file name
// and projection digest in name order.
func cardGeneration(cards []Card) string {
	h := sha256.New()
	for _, c := range cards {
		h.Write([]byte(c.Name))
		h.Write([]byte{0})
		h.Write([]byte(c.Digest))
		h.Write([]byte{'\n'})
	}
	return hex.EncodeToString(h.Sum(nil))
}

// projectCardBytes renders the generated copy used when the state root is
// outside the repository and a link cannot reach it.
func projectCardBytes(domain string, r rules.RuleRecord) []byte {
	body := strings.TrimLeft(string(r.Body), "\n")
	var b strings.Builder
	b.WriteString("---\n" + cardMarker + "\ndescription: " + rules.YAMLString(rules.CardDescription(domain, body)) + "\nglobs:\n")
	for _, g := range r.Include {
		b.WriteString("  - " + rules.YAMLString(g) + "\n")
	}
	b.WriteString("---\n\n" + body)
	return []byte(b.String())
}

// CardState is one projected card's published state.
type CardState string

const (
	// CardApplied: the native file holds exactly the projected bytes.
	CardApplied CardState = "applied"
	// CardStale: the native file exists but no longer holds the projected
	// bytes, so canonical authority moved ahead of this surface.
	CardStale CardState = "stale"
	// CardAbsent: the projected card has no native file yet.
	CardAbsent CardState = "absent"
)

// CardStatus is one card's state on the native surface.
type CardStatus struct {
	RecordID        string                    `json:"record_id"`
	Domain          string                    `json:"domain"`
	State           CardState                 `json:"state"`
	Tier            artifacts.EnforcementTier `json:"tier"`
	SourceDigest    string                    `json:"source_digest"`
	ProjectedDigest string                    `json:"projected_digest"`
	PublishedDigest string                    `json:"published_digest,omitempty"`
}

// CardAssessment is a read-only comparison of one projection against what the
// native project rule surface currently holds.
type CardAssessment struct {
	Cards []CardStatus `json:"cards"`
	// Removed names generated card files the projection no longer produces, so a
	// renamed or deleted domain is visible before any mutation.
	Removed []string `json:"removed,omitempty"`
	// Fresh reports that every projected card is applied and no dropped card
	// remains, so publishing would be a no-op.
	Fresh bool `json:"fresh"`
}

// Assess compares the projection against the native project rule surface. It
// writes nothing.
func (c ProjectCards) Assess() (CardAssessment, error) {
	assessment := CardAssessment{}
	fresh := true
	projected := map[string]bool{}
	for _, card := range c.Cards {
		projected[card.Name] = true
		status := CardStatus{
			RecordID:        card.RecordID,
			Domain:          card.Domain,
			Tier:            card.Tier,
			SourceDigest:    card.SourceDigest,
			ProjectedDigest: card.Digest,
		}
		cur, err := observeEntry(filepath.Join(c.Dir, card.Name))
		if err != nil {
			return CardAssessment{}, err
		}
		switch {
		case !cur.exists:
			status.State = CardAbsent
			fresh = false
		case card.matches(cur):
			status.State = CardApplied
			status.PublishedDigest = cur.digest
		default:
			status.State = CardStale
			status.PublishedDigest = cur.digest
			fresh = false
		}
		assessment.Cards = append(assessment.Cards, status)
	}
	removed, err := c.droppedCards(projected, nil)
	if err != nil {
		return CardAssessment{}, err
	}
	assessment.Removed = removed
	fresh = fresh && len(removed) == 0
	assessment.Fresh = fresh
	return assessment, nil
}

// entry is what one native card path holds, read without following a link.
type entry struct {
	exists, link bool
	digest       string
}

func observeEntry(path string) (entry, error) {
	fi, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return entry{}, nil
	}
	if err != nil {
		return entry{}, err
	}
	if fi.Mode()&os.ModeSymlink != 0 {
		target, err := os.Readlink(path)
		return entry{exists: true, link: true, digest: managedfile.Digest([]byte(target))}, err
	}
	obs, err := managedfile.Observe(path, managedfile.KindFile)
	return entry{exists: true, digest: obs.Digest}, err
}

func (c Card) matches(e entry) bool {
	return e.exists && e.link == (c.LinkTarget != "") && e.digest == c.Digest
}

func (c Card) kind() managedfile.Kind {
	if c.LinkTarget != "" {
		return managedfile.KindSymlink
	}
	return managedfile.KindFile
}

// cardPath is the repository-relative slash path of a domain's canonical card.
func (c ProjectCards) cardPath(domain string) string {
	return filepath.ToSlash(filepath.Join(c.StateDir, "rules", "wiki", domain+".md"))
}

// linkTarget is the link text Atomic writes for a domain's card; empty when the
// cards publish as copies.
func (c ProjectCards) linkTarget(domain string) string {
	if c.StateDir == "" {
		return ""
	}
	return "../../" + c.cardPath(domain)
}

// droppedCards names generated card entries the projection no longer produces.
// A link counts only when the ledger recorded it, or it dangles and holds the
// exact target Atomic would write for its name.
func (c ProjectCards) droppedCards(projected map[string]bool, owned func(path, digest string) bool) ([]string, error) {
	entries, err := os.ReadDir(c.Dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var dropped []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || projected[name] || !strings.HasPrefix(name, cardFilePrefix) || !strings.HasSuffix(name, ".md") {
			continue
		}
		path := filepath.Join(c.Dir, name)
		if e.Type()&os.ModeSymlink != 0 {
			target, err := os.Readlink(path)
			if err != nil {
				return nil, err
			}
			_, statErr := os.Stat(path)
			expected := c.linkTarget(strings.TrimSuffix(strings.TrimPrefix(name, cardFilePrefix), ".md"))
			if owned != nil && owned(path, managedfile.Digest([]byte(target))) || expected != "" && target == expected && errors.Is(statErr, os.ErrNotExist) {
				dropped = append(dropped, name)
			}
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		if strings.Contains(string(data), cardMarker) {
			dropped = append(dropped, name)
		}
	}
	return dropped, nil
}

// ProjectRuleTarget is the ledger target for one repository's OMP cards. Worktrees
// share it and differ by resource path, so NativeRoot stays empty.
func ProjectRuleTarget(projectKey string) harness.Target {
	return harness.Target{Kind: harness.KindOMP, Instance: projectKey}
}

// CardPublishRequest is the caller's intent to converge one repository's wiki
// cards into the OMP project rule surface.
type CardPublishRequest struct {
	Home string
	// StateRoot is the repository's selected state directory, which holds the
	// canonical rules/wiki cards.
	StateRoot string
	// ProjectKey identifies the repository across worktrees.
	ProjectKey string
	// Base is the absolute repository (or worktree) root the cards bind to.
	Base string
	// OperationID names the journal and transaction directories. Empty derives a
	// unique id from the clock.
	OperationID string
	Now         func() time.Time
	// Stage adds the visible links and the cards they point to to the Git index.
	Stage bool
}

// CardPublishResult reports what the publication planned, committed, and
// observed.
type CardPublishResult struct {
	Target harness.Target `json:"target"`
	// Dir is the native cards directory.
	Dir        string         `json:"dir"`
	Status     harness.Status `json:"status"`
	Generation string         `json:"generation"`
	Cards      []CardStatus   `json:"cards"`
	Removed    []string       `json:"removed,omitempty"`
	// Applied reports that this operation published native bytes; false means
	// the surface was already converged.
	Applied bool `json:"applied"`
	// Fresh reports whether the surface holds the projection on return; Cards and
	// Removed report the pre-mutation comparison.
	Fresh bool `json:"fresh"`
	// Retired names legacy card trees removed because their ledger rows
	// matched; Kept names legacy trees left in place because they did not.
	Retired []string `json:"retired,omitempty"`
	Kept    []string `json:"kept,omitempty"`
	// Ignored lists links a Git ignore source hides, which OMP then skips.
	Ignored     []IgnoredLink        `json:"ignored,omitempty"`
	JournalPath string               `json:"journal_path,omitempty"`
	Gaps        []harness.Capability `json:"gaps,omitempty"`
	Unproven    []PackageGap         `json:"unproven,omitempty"`
}

// IgnoredLink is a card link Git ignores, and the ignore file that does it.
type IgnoredLink struct {
	Path   string `json:"path"`
	Source string `json:"source"`
}

// PublishProjectCards converges one repository's wiki cards into the OMP project
// rule surface through the transaction engine.
func (a *Adapter) PublishProjectCards(req CardPublishRequest) (CardPublishResult, error) {
	var result CardPublishResult
	if req.Home == "" {
		return result, fmt.Errorf("omp: publish project cards: no home")
	}
	if req.Base == "" {
		return result, fmt.Errorf("omp: publish project cards: no base")
	}

	cards, err := LoadProjectCards(req.StateRoot, req.ProjectKey, req.Base, a.Capabilities())
	if err != nil {
		return result, err
	}
	target := ProjectRuleTarget(req.ProjectKey)
	result = CardPublishResult{
		Target:     target,
		Dir:        cards.Dir,
		Generation: cards.Generation,
		Gaps:       cards.Gaps,
		Unproven:   packageGaps(),
	}

	assessment, err := cards.Assess()
	if err != nil {
		return result, err
	}
	result.Cards = assessment.Cards
	result.Removed = assessment.Removed

	now := req.Now
	if now == nil {
		now = func() time.Time { return time.Now().UTC() }
	}
	operationID := req.OperationID
	if operationID == "" {
		operationID = fmt.Sprintf("omp-cards-%d", now().UnixNano())
	}

	lock, err := installstate.AcquireLock(req.Home, installstate.WriterIdentity{OperationID: operationID})
	if err != nil {
		return result, err
	}
	defer lock.Release()

	recovery, err := installstate.RecoverJournals(req.Home)
	if err != nil {
		return result, err
	}
	for _, action := range recovery {
		if action.Decision == installstate.DecisionConflict {
			return result, installstate.JournalConflictError(action.Path, action.Detail)
		}
	}

	ledger, err := installstate.LoadLedger(config.LedgerPath(req.Home))
	if err != nil {
		return result, err
	}
	// A file Atomic cannot prove it wrote is a changed derivative or the
	// repository's own rule: refused before any mutation and preserved.
	var conflicts []string
	var mutations []installstate.Mutation
	var links []Card
	staged := map[string][]byte{}
	var committed bool
	for _, card := range cards.Cards {
		path := filepath.Join(cards.Dir, card.Name)
		row := installstate.Row{
			Target:     target.Key(),
			Resource:   path,
			Consumer:   req.ProjectKey,
			Generation: cards.Generation,
			Tier:       string(Tier),
			Applied:    installstate.AppliedValue{Path: path, Kind: card.kind(), Digest: card.Digest},
		}
		cur, err := observeEntry(path)
		if err != nil {
			return result, err
		}
		if card.matches(cur) {
			// Already applied: this also adopts a committed link no ledger
			// recorded and recovers an operation interrupted before its commit.
			committed = ledger.Upsert(row) || committed
			continue
		}
		if cur.exists {
			recorded, ok := ledger.Find(target.Key(), path)
			generatedCopy := !cur.link && cur.digest == card.CopyDigest
			if !generatedCopy && (!ok || recorded.Applied.Digest == "" || recorded.Applied.Digest != cur.digest) {
				conflicts = append(conflicts, path)
				continue
			}
		}
		if card.LinkTarget != "" {
			links = append(links, card)
			continue
		}
		staged[card.Name] = card.Bytes
		mutations = append(mutations, installstate.Mutation{
			Unit:       card.Name,
			Resource:   path,
			Target:     target.Key(),
			Consumer:   req.ProjectKey,
			Generation: cards.Generation,
			Tier:       string(Tier),
			Kind:       managedfile.KindFile,
			Path:       path,
			Intended:   card.Digest,
		})
	}
	if len(conflicts) > 0 {
		result.Status = harness.StatusConflicted
		return result, fmt.Errorf("omp: publish project cards %s: %s hold bytes Atomic did not record writing; preserving them for resolution", target.Key(), strings.Join(conflicts, ", "))
	}

	if err := retireLegacyCards(ledger, cards.Base, config.LedgerPath(req.Home), &result); err != nil {
		return result, err
	}
	if len(cards.Cards) == 0 && len(assessment.Removed) == 0 {
		// Nothing is projected and nothing generated remains: no directory,
		// journal, or ledger row is written.
		result.Status = harness.StatusConverged
		result.Fresh = true
		return result, nil
	}

	owned := func(path, digest string) bool {
		recorded, ok := ledger.Find(target.Key(), path)
		return ok && recorded.Applied.Digest == digest
	}
	projected := map[string]bool{}
	for _, card := range cards.Cards {
		projected[card.Name] = true
	}
	removed, err := cards.droppedCards(projected, owned)
	if err != nil {
		return result, err
	}
	result.Removed = removed
	for _, name := range removed {
		path := filepath.Join(cards.Dir, name)
		cur, err := observeEntry(path)
		if err != nil {
			return result, err
		}
		if !cur.link && !owned(path, cur.digest) {
			result.Kept = append(result.Kept, path)
			continue
		}
		if err := os.Remove(path); err != nil {
			return result, fmt.Errorf("omp: retire card %s: %w", path, err)
		}
		ledger.Rows = slices.DeleteFunc(ledger.Rows, func(r installstate.Row) bool {
			return r.Target == target.Key() && r.Resource == path
		})
		result.Applied, committed = true, true
	}

	for _, card := range links {
		path := filepath.Join(cards.Dir, card.Name)
		if err := os.MkdirAll(cards.Dir, 0o755); err != nil {
			return result, err
		}
		// Renamed over the entry so a crash never leaves the name without a link.
		tmp, err := symlinkTemp(card.LinkTarget, path)
		if err != nil {
			return result, fmt.Errorf("omp: write card link %s: %w", path, err)
		}
		if err := os.Rename(tmp, path); err != nil {
			os.Remove(tmp)
			return result, fmt.Errorf("omp: write card link %s: %w", path, err)
		}
		ledger.Upsert(installstate.Row{
			Target: target.Key(), Resource: path, Consumer: req.ProjectKey, Generation: cards.Generation, Tier: string(Tier),
			Applied: installstate.AppliedValue{Path: path, Kind: managedfile.KindSymlink, Digest: card.Digest},
		})
		result.Applied, committed = true, true
	}

	// Rows for retired cards and written links are saved before the journaled
	// copy publication; an interrupted run is recovered by adoption on rerun.
	if committed {
		if err := ledger.Save(config.LedgerPath(req.Home)); err != nil {
			return result, err
		}
	}
	if err := exposeLinks(cards, req.Stage, &result); err != nil {
		return result, err
	}
	if len(mutations) == 0 {
		result.Status = harness.StatusConverged
		result.Fresh = len(result.Kept) == 0
		return result, nil
	}

	tx, err := installstate.NewTransaction(req.Home, operationID, installstate.Plan{Mutations: mutations})
	if err != nil {
		return result, err
	}
	tx.Ledger = ledger
	result.JournalPath = tx.JournalPath

	for _, m := range mutations {
		if _, err := tx.StageFile(m.Unit, staged[m.Unit], 0o644); err != nil {
			return result, err
		}
		if err := tx.PublishFile(m.Unit); err != nil {
			return result, err
		}
	}
	if err := tx.Complete(); err != nil {
		return result, err
	}
	if _, err := installstate.CleanupOperation(req.Home, tx.ID); err != nil {
		return result, err
	}

	result.Applied = true
	result.Status = harness.StatusConverged
	result.Fresh = len(result.Kept) == 0
	return result, nil
}

// symlinkTemp creates a link to target under a fresh name beside path, never
// reusing an existing entry.
func symlinkTemp(target, path string) (string, error) {
	for range 8 {
		tmp := path + "." + strconv.FormatUint(rand.Uint64(), 36) + ".tmp"
		err := os.Symlink(target, tmp)
		if err == nil {
			return tmp, nil
		}
		if !errors.Is(err, os.ErrExist) {
			return "", err
		}
	}
	return "", fmt.Errorf("no free temporary name beside %s", path)
}

// exposeLinks probes each link for a Git ignore rule and, when stage is set,
// adds the visible ones to the index. Outside a Git repository it does nothing.
func exposeLinks(cards ProjectCards, stage bool, result *CardPublishResult) error {
	if exec.Command("git", "-C", cards.Base, "rev-parse", "--git-dir").Run() != nil {
		return nil
	}
	var visible []string
	for _, card := range cards.Cards {
		if card.LinkTarget == "" {
			continue
		}
		rel := filepath.ToSlash(filepath.Join(ProjectRulesDir, card.Name))
		source, ignored, err := config.GitIgnoreSource(cards.Base, rel)
		if err != nil {
			return err
		}
		if ignored {
			if !filepath.IsAbs(source) {
				source = filepath.Join(cards.Base, source)
			}
			result.Ignored = append(result.Ignored, IgnoredLink{Path: filepath.Join(cards.Base, filepath.FromSlash(rel)), Source: source})
			continue
		}
		// The card the link points to goes in with it, or the commit holds a dangling link.
		visible = append(visible, rel, card.CardPath)
	}
	if !stage || len(visible) == 0 {
		return nil
	}
	out, err := exec.Command("git", append([]string{"-C", cards.Base, "add", "--"}, visible...)...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("omp: stage card links: %w: %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// retireLegacyCards removes the nested and `atomic-wiki/` card trees (and the
// nested copy's ignore rule) whose ledger row matches; any other is kept.
func retireLegacyCards(ledger *installstate.Ledger, base, ledgerPath string, result *CardPublishResult) error {
	changed := false
	for _, rel := range []string{legacyNestedCards, harness.LegacyOMPCards} {
		legacy := filepath.Join(base, filepath.FromSlash(rel))
		removed, kept, err := harness.RetireTree(ledger, legacy)
		if err != nil {
			return err
		}
		if kept {
			result.Kept = append(result.Kept, legacy)
		}
		if !removed {
			continue
		}
		changed = true
		result.Retired = append(result.Retired, legacy)
		if rel == legacyNestedCards {
			// os.Remove fails on a parent the repository put a file in; its
			// ignore line then still applies.
			if err := os.Remove(filepath.Dir(legacy)); err != nil && !errors.Is(err, os.ErrNotExist) {
				continue
			}
			if err := removeIgnoreRule(filepath.Join(base, ".omp", ".gitignore"), legacyNestedIgnoreRule); err != nil {
				return err
			}
		}
	}
	if !changed {
		return nil
	}
	return ledger.Save(ledgerPath)
}

// removeIgnoreRule drops rule from the ignore file at path, and the file when
// nothing else is left.
func removeIgnoreRule(path, rule string) error {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	var kept []string
	for _, line := range strings.Split(string(data), "\n") {
		if strings.TrimSpace(line) != rule {
			kept = append(kept, line)
		}
	}
	out := strings.Join(kept, "\n")
	switch {
	case out == string(data):
		return nil
	case strings.TrimSpace(out) == "":
		return os.Remove(path)
	}
	return os.WriteFile(path, []byte(out), 0o644)
}

// ProjectRuleStatus reports one repository's card surface without writing, for
// status and doctor.
func (a *Adapter) ProjectRuleStatus(stateRoot, projectKey, base string) (CardAssessment, []harness.Capability, error) {
	cards, err := LoadProjectCards(stateRoot, projectKey, base, a.Capabilities())
	if err != nil {
		return CardAssessment{}, nil, err
	}
	assessment, err := cards.Assess()
	if err != nil {
		return CardAssessment{}, nil, err
	}
	return assessment, cards.Gaps, nil
}

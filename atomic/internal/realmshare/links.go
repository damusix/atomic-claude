func openLocalLinks(loc bindingLocation) (*localLinks, error) {
	l, err := openLocalLinkView(loc, false)
	if err != nil {
		return nil, err
	}
	if l.binding.PendingShare != nil {
		l.close()
		return nil, fmt.Errorf("finish the pending realm share before changing local links")
	}
	return l, nil
}

func openLocalLinkView(loc bindingLocation, observe bool) (*localLinks, error) {
	b, owner, err := loc.loadBindingClaim(observe)
	if err != nil {
		return nil, err
	}
	realm, err := os.OpenRoot(loc.physicalRealm)
	if err != nil {
		return nil, err
	}
	state, err := os.OpenRoot(loc.physicalState)
	if err != nil {
		realm.Close()
		return nil, err
	}
	return &localLinks{loc: loc, binding: b, owner: owner, realm: realm, state: state}, nil
}

func (l *localLinks) close() {
	l.state.Close()
	l.realm.Close()
}

func (l *localLinks) definition(clone *os.Root) (Manifest, string, error) {
	data, err := readLocalRegular(clone, manifestName)
	if err != nil {
		return Manifest{}, "", err
	}
	var m Manifest
	if err := toml.NewDecoder(bytes.NewReader(data)).DisallowUnknownFields().Decode(&m); err != nil {
		return Manifest{}, "", fmt.Errorf("read shared realm definition: %w", err)
	}
	if m.Version != manifestVersion || m.ID != l.binding.RealmID {
		return Manifest{}, "", fmt.Errorf("shared realm definition does not match the bound identity and supported version")
	}
	state, _ := relativeTo(l.loc.physicalRealm, l.loc.physicalState)
	if err := m.validate(clone, nil, state); err != nil {
		return Manifest{}, "", err
	}
	return m, localDigest(data), nil
}

func localDigest(data []byte) string {
	return fmt.Sprintf("sha256:%x", sha256.Sum256(data))
}

func restorationFor(b Binding, name string) (RestorationReceipt, bool) {
	for _, r := range b.Restorations {
		if r.Path == name {
			return r, true
		}
	}
	return RestorationReceipt{}, false
}

func localWitnessPath(b Binding, link LinkReceipt) string {
	if link.Witness != "" {
		return link.Witness
	}
	r, _ := restorationFor(b, link.Path)
	if validLocalBackup(r.Backup) {
		return r.Backup + ".link"
	}
	return ""
}

func localLinkWitness(root, state *os.Root, b Binding, link LinkReceipt) (os.FileInfo, error) {
	proof := localWitnessPath(b, link)
	if proof == "" {
		return nil, fmt.Errorf("local link %q has no Atomic-owned symlink witness", link.Path)
	}
	witness, err := lstatBelow(state, proof)
	if err != nil || witness.Mode()&fs.ModeSymlink == 0 {
		return nil, fmt.Errorf("local link %q has no Atomic-owned symlink witness", link.Path)
	}
	target := filepath.Join(b.ClonePath, filepath.FromSlash(link.Source))
	if err := checkWitnessedLink(root, link.Path, target, witness); err != nil {
		return nil, err
	}
	return witness, nil
}

func (l *localLinks) selection(ctx context.Context, mapping Mapping) (linkSelectionReview, error) {
	s := linkSelectionReview{Mapping: mapping}
	name := mapping.Destination
	for _, active := range l.binding.Links {
		if !pathsOverlap(active.Path, name) {
			continue
		}
		if active.Path != name || active.Source != mapping.Source {
			return s, fmt.Errorf("selection %q overlaps a different owned link; unlink first", name)
		}
		_, err := localLinkWitness(l.realm, l.state, l.binding, active)
		s.Owned = active
		s.Witness = localWitnessPath(l.binding, active)
		s.Original, _ = restorationFor(l.binding, name)
		return s, err
	}
	for _, bucket := range l.binding.PrivateBuckets {
		if pathsOverlap(l.loc.bucketPath(bucket), name) {
			return s, fmt.Errorf("selection %q overlaps private bucket %q", name, bucket.Name)
		}
	}
	r, retained := restorationFor(l.binding, name)
	if retained {
		if !r.Restored {
			return s, fmt.Errorf("original %q has no completed restoration receipt", name)
		}
		s.Original = r
	}
	if p := l.binding.PendingLocal; p != nil && !p.Unlink {
		for _, change := range p.Changes {
			if change.Link.Path == name {
				if change.Link.Source != mapping.Source {
					return s, fmt.Errorf("pending link source for %q does not match the reviewed definition", name)
				}
				s.Pending = change
				err := l.pendingLinkReview(ctx, change, &s)
				return s, err
			}
		}
	}
	_, err := lstatBelow(l.realm, name)
	switch {
	case retained:
		if err != nil {
			return s, fmt.Errorf("restored original %q is unavailable: %w", name, err)
		}
		if err := checkShareMount(l.realm, name); err != nil {
			return s, err
		}
		if err := checkLocalOriginal(ctx, l.state, r.Backup, r); err != nil {
			return s, err
		}
		return s, checkLocalRestoration(ctx, l.realm, name, r, r.Identity)
	case os.IsNotExist(err):
		return s, nil
	case err != nil:
		return s, err
	default:
		return s, fmt.Errorf("local destination %q is occupied; move the private path before linking", name)
	}
}

// LinkCandidates inspects declared destinations without changing local state.
func LinkCandidates(realmRoot string) ([]LinkCandidate, error) {
	loc, err := locateBinding(realmRoot)
	if err != nil {
		return nil, err
	}
	l, err := openLocalLinks(loc)
	if err != nil {
		return nil, err
	}
	defer l.close()
	clone, err := os.OpenRoot(l.binding.ClonePath)
	if err != nil {
		return nil, err
	}
	defer clone.Close()
	m, _, err := l.definition(clone)
	if err != nil {
		return nil, err
	}
	out := make([]LinkCandidate, 0, len(m.Mappings))
	for _, mapping := range m.Mappings {
		s, err := l.selection(context.Background(), mapping)
		out = append(out, LinkCandidate{Mapping: mapping, AlreadyLinked: err == nil && s.Owned.Path != "", Collision: err != nil})
	}
	return out, nil
}

// PreviewLink checks and displays only explicitly selected local destinations.
func PreviewLink(ctx context.Context, realmRoot string, paths []string) (LinkPlan, error) {
	loc, err := locateBinding(realmRoot)
	if err != nil {
		return LinkPlan{}, err
	}
	l, err := openLocalLinks(loc)
	if err != nil {
		return LinkPlan{}, err
	}
	defer l.close()
	return l.preview(ctx, paths)
}

func (l *localLinks) preview(ctx context.Context, inputs []string) (LinkPlan, error) {
	if len(inputs) == 0 {
		return LinkPlan{}, fmt.Errorf("select at least one explicit realm-relative path to link")
	}
	state, _ := relativeTo(l.loc.physicalRealm, l.loc.physicalState)
	paths := make([]string, 0, len(inputs))
	for _, input := range inputs {
		name := strings.TrimSuffix(strings.TrimPrefix(filepath.ToSlash(input), "./"), "/")
		if err := validateDestinationPath(name, state); err != nil {
			return LinkPlan{}, err
		}
		paths = append(paths, name)
	}
	slices.Sort(paths)
	paths = slices.Compact(paths)
	b := l.binding
	if p := b.PendingLocal; p != nil {
		if p.Unlink || p.Cancel {
			return LinkPlan{}, fmt.Errorf("finish the pending realm unlink before linking")
		}
		if !slices.Equal(p.Paths, paths) {
			return LinkPlan{}, fmt.Errorf("a realm link is pending; review and repeat exactly these paths: %q", p.Paths)
		}
	}
	clone, err := os.OpenRoot(b.ClonePath)
	if err != nil {
		return LinkPlan{}, err
	}
	defer clone.Close()
	m, digest, err := l.definition(clone)
	if err != nil {
		if b.PendingLocal != nil {
			return LinkPlan{}, fmt.Errorf("cannot validate the shared definition during a pending link; use realm unlink to recover the retained paths: %w", err)
		}
		return LinkPlan{}, err
	}
	if p := b.PendingLocal; p != nil && p.Definition != digest {
		return LinkPlan{}, fmt.Errorf("shared realm definition changed during a pending link; repeat unlink to recover the retained paths")
	}
	review := &linkReview{loc: l.loc, paths: paths, approval: linkApproval{
		Owner: l.owner, State: l.loc.physicalState, TargetClone: b.ClonePath, Definition: digest, PreviousTrust: b.TrustedDigest,
		Selections: make([]linkSelectionReview, 0, len(paths)),
	}}
	selected := make([]Mapping, 0, len(paths))
	for _, name := range paths {
		i := slices.IndexFunc(m.Mappings, func(mapping Mapping) bool { return mapping.Destination == name })
		if i < 0 {
			return LinkPlan{}, fmt.Errorf("path %q is not a declared shared destination", name)
		}
		selected = append(selected, m.Mappings[i])
	}
	plan := LinkPlan{Remote: b.Remote, Branch: b.Branch, ClonePath: l.owner.Clone, review: review, Selections: make([]LinkSelection, 0, len(paths))}
	for index, mapping := range selected {
		name := mapping.Destination
		if realmArtifactRole(mapping.Kind) != "" {
			if err := validateArtifactScope(l.loc, l.realm, name); err != nil {
				return LinkPlan{}, err
			}
		}
		s, err := l.selection(ctx, mapping)
		if err != nil {
			return LinkPlan{}, err
		}
		display := LinkSelection{Mapping: mapping, AlreadyLinked: s.Owned.Path != "", RestoresOriginal: s.Owned.Path == "" && s.Original.Path != ""}
		switch mapping.Kind {
		case KindInstructions:
			team, teamErr, behavior, err := reviewTeamInstructions(ctx, clone, mapping.Source)
			if err != nil {
				return LinkPlan{}, err
			}
			s.Behavior = behavior
			display.TeamText = team
			s.Instructions = l.previewInstructions(team, teamErr)
			plan.InstructionNotes = slices.Clone(s.Instructions.Notes)
		case KindCommand, KindAgent:
			s.Behavior, err = digestSharePath(ctx, clone, mapping.Source, nil)
			if err != nil {
				return LinkPlan{}, err
			}
		case KindSkill:
			s.Behavior, err = linkSkillDigest(ctx, clone, mapping, selected)
			if err != nil {
				return LinkPlan{}, err
			}
		}
		if realmArtifactRole(mapping.Kind) != "" {
			s.Artifact, err = reviewArtifactSource(clone, mapping.Source, mapping.Kind)
			if err != nil {
				return LinkPlan{}, err
			}
			s.Effects, err = l.artifactEffects(ctx, mapping, s.Artifact.identityMissing, true)
			if err != nil {
				return LinkPlan{}, err
			}
			artifact := *s.Artifact
			artifact.Notes = slices.Clone(s.Artifact.Notes)
			artifact.Native = artifactDisplays(s.Effects)
			display.Artifact = &artifact
		}
		if mapping.Kind == KindDirectory {
			for _, bucket := range m.Buckets {
				if containsPath(name, bucket.Path) {
					s.Buckets = append(s.Buckets, bucket)
				}
			}
		}
		if p := b.PendingLocal; p != nil {
			if p.Behavior[index] != s.Behavior {
				return LinkPlan{}, fmt.Errorf("shared behavior at %q changed during a pending link; repeat unlink to recover the retained paths", name)
			}
			if display.AlreadyLinked == (s.Pending.Token != "") {
				return LinkPlan{}, fmt.Errorf("pending link receipts do not match the reviewed selection for %q", name)
			}
		}
		review.approval.Selections = append(review.approval.Selections, s)
		display.Buckets = slices.Clone(s.Buckets)
		plan.Selections = append(plan.Selections, display)
	}
	if err := ctx.Err(); err != nil {
		return LinkPlan{}, err
	}
	review.digest, err = approvalDigest("link", review.approval)
	return plan, err
}

func linkSkillDigest(ctx context.Context, clone *os.Root, skill Mapping, selected []Mapping) (string, error) {
	digest := sha256.New()
	units := []Mapping{skill}
	for i := 0; i < len(units); i++ {
		unit := units[i]
		tree, err := digestSharePath(ctx, clone, unit.Source, func(entry snapshotEntry) error {
			if entry.mode&fs.ModeSymlink == 0 {
				return nil
			}
			target := path.Join(path.Dir(entry.name), entry.target)
			if containsPath(unit.Source, target) {
				return nil
			}
			j := slices.IndexFunc(selected, func(m Mapping) bool { return containsPath(m.Source, target) })
			if j < 0 {
				return fmt.Errorf("skill %q requires shared content at %q; select its destination before linking", skill.Destination, target)
			}
			if !slices.Contains(units, selected[j]) {
				units = append(units, selected[j])
			}
			return nil
		})
		if err != nil {
			return "", err
		}
		fmt.Fprintf(digest, "%q %s\n", unit.Source, tree)
	}
	return fmt.Sprintf("sha256:%x", digest.Sum(nil)), nil
}

// ApplyLink revalidates the reviewed definition and destinations under the realm writer lock.
func ApplyLink(ctx context.Context, plan LinkPlan) error {
	if plan.review == nil {
		return fmt.Errorf("link requires a reviewed plan from PreviewLink")
	}
	review := plan.review
	lock, err := review.loc.lockShare()
	if err != nil {
		return err
	}
	defer lock.Release()
	loc, err := locateBinding(review.loc.realm)
	if err != nil {
		return err
	}
	l, err := openLocalLinks(loc)
	if err != nil {
		return err
	}
	defer l.close()
	current, err := l.preview(ctx, review.paths)
	if err != nil {
		return err
	}
	if loc != review.loc || current.ReviewDigest() != review.digest {
		return fmt.Errorf("realm identity, shared definition, selected behavior, or local activation effects changed after review; preview again before linking")
	}
	b := l.binding
	p := b.PendingLocal
	if p == nil {
		p = &pendingLocal{Definition: review.approval.Definition, Paths: review.paths, Behavior: make([]string, 0, len(review.paths))}
		for _, s := range review.approval.Selections {
			p.Behavior = append(p.Behavior, s.Behavior)
			if s.Owned.Path != "" {
				continue
			}
			id := rand.Text()
			change := localChange{Token: id, Link: LinkReceipt{Path: s.Mapping.Destination, Source: s.Mapping.Source, Witness: path.Join(shareBackupDir, id+".link")}}
			change.RestoreID = s.Original.Identity
			p.Changes = append(p.Changes, change)
		}
		for _, s := range review.approval.Selections {
			for _, effect := range s.Effects {
				if effect.State != "ready" || effect.Owned.Path != "" || effect.Path == s.Mapping.Destination {
					continue
				}
				id := rand.Text()
				p.Changes = append(p.Changes, localChange{
					Token: id, Artifact: s.Mapping.Destination,
					Link: LinkReceipt{Path: effect.Path, Source: s.Mapping.Source, Witness: path.Join(shareBackupDir, id+".link")},
				})
			}
		}
	}
	approvedArtifacts := approvedArtifactVersions(b, p.Changes, current.review.approval.Selections)
	switch {
	case len(p.Changes) != 0:
		if err := l.applyLocal(ctx, p, approvedArtifacts); err != nil {
			return err
		}
	default:
		changed, err := l.recordArtifactVersions(&b, approvedArtifacts)
		if err != nil {
			return err
		}
		if changed || b.TrustedDigest != p.Definition {
			b.TrustedDigest = p.Definition
			if err := loc.saveBinding(b); err != nil {
				return err
			}
			l.binding = b
		} else if err := l.syncBindingDirectory(); err != nil {
			return err
		}
	}
	for _, s := range current.review.approval.Selections {
		if s.Instructions != nil {
			if err := l.applyInstructions(ctx, s.Instructions, p.Definition, s.Behavior); err != nil {
				return fmt.Errorf("realm links are recorded, but local instruction activation did not finish; review and repeat the instruction link: %w", err)
			}
		}
	}
	return nil
}

// Unlink removes only witnessed local links and restores independently retained originals.
func Unlink(ctx context.Context, realmRoot string) error {
	loc, err := locateBinding(realmRoot)
	if err != nil {
		return err
	}
	lock, err := loc.lockShare()
	if err != nil {
		return err
	}
	defer lock.Release()
	if current, err := locateBinding(loc.realm); err != nil {
		return err
	} else if current != loc {
		return fmt.Errorf("realm state location changed while acquiring the writer lock")
	}
	l, err := openLocalLinks(loc)
	if err != nil {
		return err
	}
	defer l.close()
	p := l.binding.PendingLocal
	if p != nil && !p.Unlink {
		if err := l.cancelLocalLink(ctx, p); err != nil {
			return err
		}
		p = nil
	}
	if p == nil {
		if len(l.binding.Links) == 0 {
			return l.syncBindingDirectory()
		}
		p = &pendingLocal{Unlink: true}
		for _, artifact := range l.binding.Artifacts {
			p.Changes = append(p.Changes, localChange{Token: rand.Text(), Artifact: artifact.Logical, Link: artifact.Link})
		}
		for _, link := range l.binding.Links {
			p.Changes = append(p.Changes, localChange{Token: rand.Text(), Link: link})
		}
	}
	return l.applyLocal(ctx, p, nil)
}

func readLocalRegular(root *os.Root, name string) ([]byte, error) {
	info, err := lstatBelow(root, name)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("%q must be a regular file", name)
	}
	file, err := root.Open(name)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	opened, err := file.Stat()
	if err != nil {
		return nil, err
	}
	if !os.SameFile(info, opened) {
		return nil, fmt.Errorf("%q changed while opening it", name)
	}
	data, err := io.ReadAll(file)
	if err != nil {
		return nil, err
	}
	current, err := lstatBelow(root, name)
	if err != nil {
		return nil, err
	}
	if !os.SameFile(info, current) || int64(len(data)) != info.Size() || !info.ModTime().Equal(current.ModTime()) {
		return nil, fmt.Errorf("%q changed while reading it", name)
	}
	return data, nil
}

func ensureLocalParent(root *os.Root, name string) error {
	if name == "." {
		return nil
	}
	parent := path.Dir(name)
	if err := ensureLocalParent(root, parent); err != nil {
		return err
	}
	info, err := lstatBelow(root, name)
	if os.IsNotExist(err) {
		if err := root.Mkdir(name, 0o755); err != nil && !os.IsExist(err) {
			return err
		}
		info, err = lstatBelow(root, name)
	}
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return fmt.Errorf("destination parent %q must be a real directory", name)
	}
	dir, err := openShareDirectory(root, parent)
	if err != nil {
		return err
	}
	defer dir.Close()
	if err := dir.Sync(); err != nil {
		return err
	}
	if err := checkLocalDirectory(root, parent, dir); err != nil {
		return err
	}
	current, err := lstatBelow(root, name)
	if err != nil {
		return err
	}
	if !os.SameFile(info, current) {
		return fmt.Errorf("destination parent %q changed while making it durable", name)
	}
	return nil
}

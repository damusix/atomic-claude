const shareBackupDir = "realm-share-backups"

func scanSharePath(ctx context.Context, realm *os.Root, mapping Mapping) (pendingPath, []snapshotEntry, error) {
	result := pendingPath{ShareSelection: ShareSelection{Mapping: mapping}}
	if err := checkShareMount(realm, mapping.Destination); err != nil {
		return result, nil, err
	}
	var entries []snapshotEntry
	var excluded string
	digest, err := digestSharePath(ctx, realm, mapping.Destination, func(e snapshotEntry) error {
		if strings.EqualFold(e.name, "wiki/index.md") && e.name != "wiki/index.md" {
			return fmt.Errorf("wiki index path %q must use the spelling wiki/index.md", e.name)
		}
		if e.name != mapping.Destination {
			if excluded != "" && containsPath(excluded, e.name) {
				return nil
			}
			if strings.EqualFold(path.Base(e.name), ".git") {
				if mapping.Destination != "wiki" || e.name != "wiki/.git" || !e.mode.IsDir() {
					return fmt.Errorf("nested Git repository at %q; only an entire wiki with a real .git directory can be snapshotted", path.Dir(e.name))
				}
				result.Exclusions = append(result.Exclusions, e.name+" (history kept in the local backup)")
				excluded = e.name
				return nil
			}
			if !portablePath(e.name) {
				return fmt.Errorf("unsupported selected path %q; names must be portable", e.name)
			}
			if err := validateSharedPath(e.name); err != nil {
				result.Exclusions = append(result.Exclusions, e.name+" (local only)")
				if e.mode.IsDir() {
					excluded = e.name
				}
				return nil
			}
		}
		if e.mode.IsDir() {
			bare, err := shareHasBareGit(realm, e.name)
			if err != nil {
				return err
			}
			if bare {
				return fmt.Errorf("nested bare Git repository at %q cannot be shared", e.name)
			}
			return nil
		}
		if !e.mode.IsRegular() && e.mode&fs.ModeSymlink == 0 {
			return fmt.Errorf("unsupported selected file %q (%s)", e.name, e.mode)
		}
		if e.name == "wiki/index.md" || (e.name == "wiki/README.md" && e.mode.IsRegular()) {
			if !e.mode.IsRegular() {
				return fmt.Errorf("wiki index must be a regular file")
			}
			data, err := realm.ReadFile(e.name)
			if err != nil {
				return err
			}
			if fmt.Sprintf("%x", sha256.Sum256(data)) != e.digest {
				return fmt.Errorf("%s changed during review", e.name)
			}
			original := string(data)
			content := original
			switch e.name {
			case "wiki/index.md":
				for _, tag := range []string{"wiki-buckets", "wiki-bucket-list", "wiki-scan"} {
					if start := strings.Index(content, "<"+tag); start >= 0 {
						close := "</" + tag + ">"
						end := strings.Index(content[start:], close)
						if end < 0 {
							return fmt.Errorf("unclosed generated <%s> block in wiki/index.md", tag)
						}
						content = content[:start] + content[start+end+len(close):]
						result.Exclusions = append(result.Exclusions, "wiki/index.md <"+tag+"> (local registry)")
					}
				}
			case "wiki/README.md":
				content, err = projectWikiREADME(content, realm.Name())
				if err != nil {
					return err
				}
				if content != original {
					result.Exclusions = append(result.Exclusions, "wiki/README.md **Realm root:** (local scaffold)")
				}
			}
			if content != original {
				e.projected, e.content = true, content
				e.size = int64(len(content))
			}
		}
		entries = append(entries, e)
		return nil
	})
	result.Digest = digest
	return result, entries, err
}

func projectWikiREADME(content, realmRoot string) (string, error) {
	const title = "# Project wiki"
	const intro = "Cross-repository knowledge layer generated by `atomic wiki scan`."
	eol := "\n"
	if strings.HasPrefix(content, title+"\r\n") {
		eol = "\r\n"
	}
	header := title + eol + eol + intro + eol + eol
	field, ok := strings.CutPrefix(content, header+"**Realm root:**")
	if !ok {
		return content, nil
	}
	if field, ok := strings.CutPrefix(field, " `"); ok {
		close := "`" + eol + eol
		if afterRoot, ok := strings.CutPrefix(field, realmRoot); ok && strings.HasPrefix(afterRoot, close) {
			return header + afterRoot[len(close):], nil
		}
		line, rest, _ := strings.Cut(field, eol)
		root, closed := strings.CutSuffix(line, "`")
		rest, blank := strings.CutPrefix(rest, eol)
		if closed && blank && filepath.IsAbs(root) && !strings.ContainsAny(root, "`\r\n") {
			return header + rest, nil
		}
	}
	return "", errors.New("cannot identify the generated realm root field in wiki/README.md; remove the field before sharing")
}

func shareHasBareGit(root *os.Root, name string) (bool, error) {
	for _, part := range []string{"HEAD", "objects", "refs"} {
		info, err := root.Lstat(path.Join(name, part))
		if os.IsNotExist(err) {
			return false, nil
		}
		if err != nil {
			return false, err
		}
		if info.Mode()&fs.ModeSymlink != 0 {
			continue
		}
		if part == "HEAD" && !info.Mode().IsRegular() || part != "HEAD" && !info.IsDir() {
			return false, nil
		}
	}
	return true, nil
}

func digestSharePath(ctx context.Context, root *os.Root, name string, visit func(snapshotEntry) error) (string, error) {
	if _, err := lstatBelow(root, name); err != nil {
		return "", err
	}
	tree := sha256.New()
	err := fs.WalkDir(root.FS(), name, func(nameInTree string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if err := ctx.Err(); err != nil {
			return err
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		e := snapshotEntry{name: nameInTree, mode: info.Mode(), size: info.Size()}
		switch {
		case e.mode.IsRegular():
			f, err := openRegular(root, e.name)
			if err != nil {
				return err
			}
			h := sha256.New()
			n, copyErr := io.Copy(h, f)
			if err := errors.Join(copyErr, f.Close()); err != nil {
				return err
			}
			if n != e.size {
				return fmt.Errorf("file %q changed while being read", e.name)
			}
			e.digest = fmt.Sprintf("%x", h.Sum(nil))
		case e.mode&fs.ModeSymlink != 0:
			e.target, err = root.Readlink(e.name)
			if err != nil {
				return err
			}
			e.size = int64(len(e.target))
		}
		fmt.Fprintf(tree, "%q %o %q %s\n", strings.TrimPrefix(e.name, name), e.mode, e.target, e.digest)
		if visit != nil {
			return visit(e)
		}
		return nil
	})
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("sha256:%x", tree.Sum(nil)), nil
}

func (st *sharePlanState) validateSelectionLinks() error {
	sources := make(map[string]sourceEntry)
	prefixes := make(map[string]string)
	for _, existing := range st.manifest.Mappings {
		if err := recordPathPrefixes(prefixes, existing.Source); err != nil {
			return err
		}
	}
	for _, selected := range st.paths {
		if err := recordPathPrefixes(prefixes, selected.Mapping.Source); err != nil {
			return err
		}
	}
	for _, files := range st.entries {
		for _, entry := range files {
			if err := rememberSource(sources, entry.name, entry.mode.Type()); err != nil {
				return err
			}
			for dir := path.Dir(entry.name); dir != "."; dir = path.Dir(dir) {
				if err := rememberSource(sources, dir, fs.ModeDir); err != nil {
					return err
				}
			}
		}
	}
	graph := make(directoryLinks)
	for _, files := range st.entries {
		for _, entry := range files {
			if entry.mode&fs.ModeSymlink == 0 {
				continue
			}
			target := entry.target
			for strings.HasPrefix(target, "../") {
				target = target[3:]
			}
			resolved := path.Join(path.Dir(entry.name), entry.target)
			dst := sources[strings.ToLower(resolved)]
			if !portablePath(target) || !portablePath(resolved) || dst.name != resolved || dst.mode == fs.ModeSymlink || !slices.ContainsFunc(st.paths, func(s pendingPath) bool {
				return containsPath(s.Mapping.Source, resolved)
			}) {
				return fmt.Errorf("symlink %q -> %q requires its direct target in the selected content", entry.name, entry.target)
			}
			if dst.mode.IsDir() {
				graph.add(path.Dir(entry.name), resolved)
			}
		}
	}
	return graph.checkCycles()
}

func probeShareSymlinks(realm string) error {
	temp, err := os.MkdirTemp(realm, ".atomic-share-probe-")
	if err != nil {
		return err
	}
	defer os.Remove(temp)
	link := filepath.Join(temp, "link")
	if err := os.Symlink(temp, link); err != nil {
		return fmt.Errorf("native symlinks are unavailable for %q; enable symlink creation before sharing: %w", realm, err)
	}
	return os.Remove(link)
}

func openShareDirectory(root *os.Root, name string) (*os.File, error) {
	before, err := lstatBelow(root, name)
	if err != nil {
		return nil, err
	}
	if !before.IsDir() {
		return nil, fmt.Errorf("share directory %q must be a real directory", name)
	}
	dir, err := root.Open(name)
	if err != nil {
		return nil, err
	}
	opened, err := dir.Stat()
	if err != nil {
		dir.Close()
		return nil, err
	}
	if !os.SameFile(before, opened) {
		dir.Close()
		return nil, fmt.Errorf("share directory %q changed while opening it", dir.Name())
	}
	return dir, nil
}

func checkShareMount(realm *os.Root, name string) error {
	parent, err := openShareDirectory(realm, path.Dir(name))
	if err != nil {
		return err
	}
	defer parent.Close()
	mounted, err := shareEntryIsMount(parent, path.Base(name))
	if err != nil {
		return fmt.Errorf("cannot check whether selected path %q is a mount point: %w", name, err)
	}
	if mounted {
		return fmt.Errorf("selected path %q is a mount point; select content that can be moved to the local backup", name)
	}
	return nil
}

func syncShareDirectories(dirs ...*os.File) error {
	var result error
	for _, dir := range dirs {
		if err := dir.Sync(); err != nil {
			result = errors.Join(result, err)
		}
	}
	return result
}

func openShareBackups(state *os.Root) (*os.Root, error) {
	if err := state.Mkdir(shareBackupDir, 0o700); err == nil {
		dir, err := openShareDirectory(state, ".")
		if err != nil {
			return nil, err
		}
		defer dir.Close()
		if err := syncShareDirectories(dir); err != nil {
			return nil, err
		}
	} else if !os.IsExist(err) {
		return nil, err
	}
	if err := checkDirectory(state, shareBackupDir); err != nil {
		return nil, err
	}
	return state.OpenRoot(shareBackupDir)
}

func shareTarget(binding Binding, mapping Mapping) string {
	return filepath.Join(binding.ClonePath, filepath.FromSlash(mapping.Source))
}

func verifyShareLink(realm *os.Root, binding Binding, mapping Mapping) error {
	for _, link := range binding.Links {
		if link.Path != mapping.Destination || link.Source != mapping.Source {
			continue
		}
		loc, err := locateBinding(realm.Name())
		if err != nil {
			return err
		}
		state, err := os.OpenRoot(loc.physicalState)
		if err != nil {
			return err
		}
		defer state.Close()
		if _, err := localLinkWitness(realm, state, binding, link); err != nil {
			return err
		}
		_, err = os.Stat(shareTarget(binding, mapping))
		return err
	}
	return fmt.Errorf("shared path %q has no owned local link; use realm link", mapping.Destination)
}

func checkShareLink(realm *os.Root, name, target string, witness os.FileInfo) error {
	if err := checkWitnessedLink(realm, name, target, witness); err != nil {
		return err
	}
	_, err := os.Stat(target)
	return err
}

func checkWitnessedLink(realm *os.Root, name, target string, witness os.FileInfo) error {
	info, err := lstatBelow(realm, name)
	if err != nil {
		return err
	}
	if witness != nil && !os.SameFile(info, witness) {
		return fmt.Errorf("local link %q does not match the Atomic-owned symlink", name)
	}
	got, err := realm.Readlink(name)
	if err != nil || got != target {
		return fmt.Errorf("local link %q does not match its recorded target %q", name, target)
	}
	if witness != nil {
		info, err := lstatBelow(realm, name)
		if err != nil {
			return err
		}
		if !os.SameFile(info, witness) {
			return fmt.Errorf("local link %q changed while checking ownership", name)
		}
	}
	return nil
}

type shareLinkState uint8

const (
	shareOriginal shareLinkState = iota
	shareBackedUp
	shareLinked
)

func shareOriginalState(ctx context.Context, realm, state *os.Root, binding Binding, selected pendingPath) (shareLinkState, error) {
	return inspectShareOriginal(ctx, realm, state, binding, selected, false)
}

func inspectShareOriginal(ctx context.Context, realm, state *os.Root, binding Binding, selected pendingPath, observe bool) (shareLinkState, error) {
	name := selected.Mapping.Destination
	if selected.Parking != "" && state != nil {
		parked := path.Join(shareBackupDir, selected.Parking)
		present, owned, err := inspectShareParking(state, parked, selected.Backup+".link")
		if err != nil {
			return 0, fmt.Errorf("cannot inspect rollback parking for %q at %q: %w", name, filepath.Join(state.Name(), parked), err)
		}
		if present && !owned {
			return 0, fmt.Errorf("unowned replacement for %q is parked at %q; recover it before retrying", name, filepath.Join(state.Name(), parked))
		}
	}
	local, err := lstatBelow(realm, name)
	if err != nil && !os.IsNotExist(err) {
		return 0, err
	}
	var backup os.FileInfo
	if state != nil {
		backup, err = lstatBelow(state, selected.Backup)
		if err != nil && !os.IsNotExist(err) {
			return 0, err
		}
	}
	if backup != nil {
		if !backup.IsDir() && !backup.Mode().IsRegular() {
			return 0, fmt.Errorf("retained backup for %q must be a regular file or real directory", name)
		}
		digest, err := digestSharePath(ctx, state, selected.Backup, nil)
		if err != nil {
			return 0, err
		}
		if digest != selected.Digest {
			return 0, fmt.Errorf("retained backup for %q changed; recover it before retrying", name)
		}
		if local == nil {
			return shareBackedUp, nil
		}
		if err := checkOwnedShareLink(realm, state, binding, selected, observe); err != nil {
			return 0, fmt.Errorf("will not overwrite an occupied path with a retained backup: %w", err)
		}
		return shareLinked, nil
	}
	if local == nil || local.Mode()&fs.ModeSymlink != 0 {
		return 0, fmt.Errorf("original %q is missing or replaced without an owned backup", name)
	}
	if err := checkShareMount(realm, name); err != nil {
		return 0, err
	}
	digest, err := digestSharePath(ctx, realm, name, nil)
	if err != nil {
		return 0, err
	}
	if digest != selected.Digest {
		return 0, fmt.Errorf("original %q changed since review; restore the reviewed version before retrying", name)
	}
	return shareOriginal, nil
}

func checkOwnedShareLink(realm, state *os.Root, binding Binding, selected pendingPath, observe bool) error {
	name := selected.Mapping.Destination
	witness, err := lstatBelow(state, selected.Backup+".link")
	if err != nil || witness.Mode()&fs.ModeSymlink == 0 {
		return fmt.Errorf("%q has no Atomic-owned symlink witness", name)
	}
	target := shareTarget(binding, selected.Mapping)
	if observe {
		return checkWitnessedLink(realm, name, target, witness)
	}
	return checkShareLink(realm, name, target, witness)
}

func stageShareLink(backups *os.Root, dir *os.File, proof, stage, target string) (os.FileInfo, error) {
	witness, err := backups.Lstat(proof)
	if os.IsNotExist(err) {
		if err := os.Symlink(target, filepath.Join(backups.Name(), proof)); err != nil {
			return nil, err
		}
		witness, err = backups.Lstat(proof)
	}
	if err != nil {
		return nil, err
	}
	if err := checkShareLink(backups, proof, target, witness); err != nil {
		return nil, err
	}
	// The witness survives a crash before the ownership receipts are written.
	if err := backups.Link(proof, stage); err != nil && !os.IsExist(err) {
		return nil, err
	}
	entry, err := backups.Lstat(stage)
	if err != nil {
		return nil, err
	}
	if !os.SameFile(witness, entry) {
		return nil, fmt.Errorf("staged path %q does not match the Atomic-owned symlink; leave it in place for recovery", filepath.Join(backups.Name(), stage))
	}
	if err := syncShareDirectories(dir); err != nil {
		return nil, err
	}
	return witness, nil
}

func inspectShareParking(root *os.Root, parked, proof string) (present, owned bool, err error) {
	entry, err := lstatBelow(root, parked)
	if os.IsNotExist(err) {
		return false, false, nil
	}
	if err != nil {
		return false, false, err
	}
	witness, err := lstatBelow(root, proof)
	if err != nil && !os.IsNotExist(err) {
		return true, false, err
	}
	return true, witness != nil && witness.Mode()&fs.ModeSymlink != 0 && os.SameFile(entry, witness), nil
}

func (st *sharePlanState) resolveShareParking(backups *os.Root, b Binding, selected *pendingPath, originalDir, backupDir *os.File) error {
	name, parked := selected.Mapping.Destination, selected.Parking
	parkedPath := filepath.Join(backups.Name(), parked)
	present, owned, err := inspectShareParking(backups, parked, path.Base(selected.Backup)+".link")
	if err != nil {
		return fmt.Errorf("cannot inspect rollback parking for %q at %q: %w", name, parkedPath, err)
	}
	if owned {
		if err := backups.Remove(parked); err != nil {
			return fmt.Errorf("cannot remove an owned link parked for %q at %q: %w", name, parkedPath, err)
		}
	} else if present {
		if err := renameShareNoReplace(backupDir, parked, originalDir, path.Base(name)); err != nil {
			return fmt.Errorf("cannot restore a replacement to %q without overwriting; retained at %q: %w", name, parkedPath, err)
		}
	}
	if err := syncShareDirectories(backupDir, originalDir); err != nil {
		return fmt.Errorf("cannot sync rollback for %q at %q: %w", name, parkedPath, err)
	}
	selected.Parking = ""
	if err := st.loc.saveBinding(b); err != nil {
		selected.Parking = parked
		return err
	}
	if present && !owned {
		return fmt.Errorf("path %q changed during rollback; its replacement was restored from %q", name, parkedPath)
	}
	return nil
}

func (st *sharePlanState) rollbackShareLink(realm, backups *os.Root, b Binding, selected *pendingPath, originalDir, backupDir *os.File, witness os.FileInfo) error {
	name := selected.Mapping.Destination
	local, err := lstatBelow(realm, name)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !os.SameFile(local, witness) {
		return fmt.Errorf("will not remove a replacement at %q", name)
	}
	selected.Parking = shareParkingPrefix + rand.Text()
	if err := st.loc.saveBinding(b); err != nil {
		return err
	}
	parkedPath := filepath.Join(backups.Name(), selected.Parking)
	if err := renameShareNoReplace(originalDir, path.Base(name), backupDir, selected.Parking); err != nil {
		return fmt.Errorf("cannot park %q for rollback at %q: %w", name, parkedPath, err)
	}
	if err := syncShareDirectories(backupDir, originalDir); err != nil {
		return fmt.Errorf("cannot sync rollback for %q at %q: %w", name, parkedPath, err)
	}
	return st.resolveShareParking(backups, b, selected, originalDir, backupDir)
}

func (st *sharePlanState) cutoverShare(ctx context.Context, b Binding) error {
	realm, err := os.OpenRoot(st.loc.physicalRealm)
	if err != nil {
		return err
	}
	defer realm.Close()
	state, err := os.OpenRoot(st.loc.physicalState)
	if err != nil {
		return err
	}
	defer state.Close()
	backups, err := openShareBackups(state)
	if err != nil {
		return err
	}
	defer backups.Close()
	backupDir, err := openShareDirectory(backups, ".")
	if err != nil {
		return err
	}
	defer backupDir.Close()
	pending := b.PendingShare
	positions := make([]shareLinkState, 0, len(pending.Selections))
	for _, selected := range pending.Selections {
		position, err := shareOriginalState(ctx, realm, state, b, selected)
		if err != nil {
			return err
		}
		positions = append(positions, position)
	}
	parents := make(map[string]*os.File)
	defer func() {
		for _, dir := range parents {
			dir.Close()
		}
	}()
	undo := make([]func() error, 0, len(positions))
	rollback := func(cause error) error {
		for i := len(undo) - 1; i >= 0; i-- {
			cause = errors.Join(cause, undo[i]())
		}
		return cause
	}
	for i := range pending.Selections {
		selected := &pending.Selections[i]
		name := selected.Mapping.Destination
		parent := path.Dir(name)
		originalDir := parents[parent]
		if originalDir == nil {
			originalDir, err = openShareDirectory(realm, parent)
			if err != nil {
				return rollback(err)
			}
			parents[parent] = originalDir
		}
		if selected.Parking != "" {
			if err := st.resolveShareParking(backups, b, selected, originalDir, backupDir); err != nil {
				return rollback(err)
			}
		}
		if positions[i] != shareLinked {
			base, backup := path.Base(name), path.Base(selected.Backup)
			proof, stage := backup+".link", backup+".link-stage"
			target := shareTarget(b, selected.Mapping)
			witness, err := stageShareLink(backups, backupDir, proof, stage, target)
			if err != nil {
				return rollback(err)
			}
			if positions[i] == shareOriginal {
				backupPath := filepath.Join(backups.Name(), backup)
				if err := renameShareNoReplace(originalDir, base, backupDir, backup); err != nil {
					return rollback(fmt.Errorf("could not retain original %q at %q: %w", name, backupPath, err))
				}
				undo = append(undo, func() error {
					if selected.Parking != "" {
						return fmt.Errorf("original for %q retained at %q until rollback parking at %q is resolved", name, backupPath, filepath.Join(backups.Name(), selected.Parking))
					}
					if err := renameShareNoReplace(backupDir, backup, originalDir, base); err != nil {
						return fmt.Errorf("could not restore %q without replacing another entry; original retained at %q: %w", name, backupPath, err)
					}
					return syncShareDirectories(originalDir, backupDir)
				})
				if err := syncShareDirectories(backupDir, originalDir); err != nil {
					return rollback(err)
				}
				if _, err := shareOriginalState(ctx, realm, state, b, *selected); err != nil {
					return rollback(err)
				}
			}
			if err := renameShareNoReplace(backupDir, stage, originalDir, base); err != nil {
				return rollback(fmt.Errorf("cannot install the owned link at %q: %w", name, err))
			}
			undo = append(undo, func() error {
				return st.rollbackShareLink(realm, backups, b, selected, originalDir, backupDir, witness)
			})
		}
	}
	if err := syncShareDirectories(backupDir); err != nil {
		return rollback(err)
	}
	for _, dir := range parents {
		if err := syncShareDirectories(dir); err != nil {
			return rollback(err)
		}
	}
	for _, selected := range pending.Selections {
		if err := checkOwnedShareLink(realm, state, b, selected, false); err != nil {
			return rollback(err)
		}
	}
	for _, selected := range pending.Selections {
		name := selected.Mapping.Destination
		b.Links = append(b.Links, LinkReceipt{Path: name, Source: selected.Mapping.Source})
		b.Restorations = append(b.Restorations, RestorationReceipt{Path: name, Digest: selected.Digest, Backup: selected.Backup})
	}
	b.PrivateBuckets = slices.DeleteFunc(slices.Clone(b.PrivateBuckets), func(bucket Bucket) bool {
		return slices.Contains(pending.Buckets, Bucket{Name: bucket.Name, Path: st.loc.bucketPath(bucket)})
	})
	b.PendingShare = nil
	if err := st.loc.saveBinding(b); err != nil {
		return err
	}
	return nil
}

